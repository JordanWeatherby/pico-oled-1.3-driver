class OLED_1inch3_SPI(framebuf.FrameBuffer):
    def __init__(self):
        
        self.is_on=0
        self.width = 128
        self.height = 64

        self.white =   0xffff
        self.black =   0x0000
        self.brightness = -1

        self.font=BasicFontCondensed

        # framebuf init
        self.buffer = bytearray(self.height * self.width // 8)
        super().__init__(self.buffer, self.width, self.height, framebuf.MONO_HMSB)

        # SPI init
        self.cs = Pin(CS,Pin.OUT)
        self.rst = Pin(RST,Pin.OUT)

        self.cs(1)
        self.spi = SPI(1)
        self.spi = SPI(1,2000_000)
        self.spi = SPI(1,20000_000,polarity=0, phase=0,sck=Pin(SCK),mosi=Pin(MOSI),miso=None)
        self.dc = Pin(DC,Pin.OUT)
        self.dc(1)

        # display init
        self.init_display()

        # Clear the screen on init - needs frambuf init, spi init and display init
        self.clear()

        # Init Keys
        self.KEY0=KEY0
        self.KEY1=KEY1
        self.key0=Pin(KEY0,Pin.IN,Pin.PULL_UP)
        self.key1=Pin(KEY1,Pin.IN,Pin.PULL_UP)

    def is_pressed(self, key):
        if key == self.KEY0:
            return not(self.key0.value())
        elif key == self.KEY1:
            return not(self.key1.value())
        else:
            return None
    
    def key_0_pressed(self):
        return not(self.key0.value())
    
    def key_1_pressed(self):
        return not(self.key1.value())

    def on(self):
        if not self.is_on:
            self.write_cmd(0xAF)
            self.is_on=1

    def off(self):
        if self.is_on:
            self.write_cmd(0xAE)
            self.is_on=0

    def get_width(self):
        return self.width

    def get_height(self):
        return self.height

    def write_cmd(self, cmd):
        self.cs(1)
        self.dc(0)
        self.cs(0)
        self.spi.write(bytearray([cmd]))
        self.cs(1)

    def write_data(self, buf):
        self.cs(1)
        self.dc(1)
        self.cs(0)
        self.spi.write(buf)
        self.cs(1)

    def _get_brightness(self):
        if (self.brightness == 1):
            return 0x00
        if (self.brightness == 2):
            return 0x4d
        if (self.brightness == 3):
            return 0x80
        if (self.brightness == 4):
            return 0xe3
        if (self.brightness == 5):
            return 0xff
        else:
            return 0x80
        
    def set_brightness(self, level):

        self.brightness = level

        # Send contrast command
        self.write_cmd(0x81)
        self.write_cmd(self._get_brightness())


    def init_display(self):
        """Initialise display"""
        self.rst(1)
        time.sleep(0.001)
        self.rst(0)
        time.sleep(0.01)
        self.rst(1)

        self.off()

        self.write_cmd(0x00)   # Set lower column address
        self.write_cmd(0x10)   # Set higher column address

        self.write_cmd(0xB0)   # Set page address

        self.write_cmd(0xdc)   # Set display start line
        self.write_cmd(0x00)   # (2nd param)

        self.write_cmd(0x81)   # Contrast control
        self.write_cmd(self._get_brightness())

        self.write_cmd(0x21)   # Set Memory addressing mode (0x20/0x21)
        self.write_cmd(0xa0)   # Set segment remap (no rotation)
        self.write_cmd(0xc0)   # Com scan direction
        self.write_cmd(0xa4)   # Disable Entire Display On (0xA4/0xA5)
        self.write_cmd(0xa6)   # Normal / reverse

        self.write_cmd(0xa8)   # Multiplex ratio - 63 for display rows
        self.write_cmd(0x3f)   # Duty = 1/64 - display each row for 1/64th of the cycle

        self.write_cmd(0xd3)   # Set display offset
        self.write_cmd(0x60)

        self.write_cmd(0xd5)   # Set osc division
        self.write_cmd(0x50)

        self.write_cmd(0xd9)   # Set pre-charge period
        self.write_cmd(0x22)

        self.write_cmd(0xdb)   # Set vcomh
        self.write_cmd(0x35)

        self.write_cmd(0xad)   # Set charge pump enable
        self.write_cmd(0x8a)   # Set DC-DC enable (a=0:disable; a=1:enable)

        self.on()

    def show(self):
        self.write_cmd(0xb0)

        for page in range(64):
            column = 63 - page

            self.write_cmd(0x00 | (column & 0x0F))
            self.write_cmd(0x10 | (column >> 4))

            start = page * 16
            end = start + 16

            # write 16 bytes at once
            self.write_data(self.buffer[start:end])

        self.fill(self.black)

    def clear(self):
        self.fill(self.black)
        self.show()

    def text(self,s,x0,y0,col=0xffff):
        x=x0
        for i in range(len(s)):
            C = ord(s[i])
            if C < 32 or C > 127:
                C = 32
            cdata = self.font[C - 32]
            if x+len(cdata) > self.width:
                x=0
                y0=y0+9
            for j in range(len(cdata)):
                if 0 <= x and x < self.width:
                    vline_data = cdata[j]
                    y = y0
                    while vline_data:
                        if  vline_data & 1:
                            if  0 <= y and y < self.height:
                                self.pixel(x, y, col);
                        vline_data=vline_data>>1
                        y=y+1
                x=x+1
        return [x,y0+9]
    
def get():
    global display
    if display is None:
        display=OLED_1inch3_SPI()
    return display



